/**
 * A 5x7 block font, shared by the rasterisers that have to put legible text into pixels without a
 * font engine.
 *
 * Two renderers use this: the brand-mark rasteriser in `src/logo-maker/raster.ts`, which draws a
 * wordmark into a PNG so a designer can see the mark without a browser, and the Employee ID Card
 * rasteriser in `src/tools/business/id-card/raster.ts`, which exists so a card's QR symbol and
 * Code 128 barcode can be decoded back out of pixels by the test suite.
 *
 * It is a *verification* font, and its limits should stay visible:
 *
 *   - glyphs are uppercase by design; lowercase input is drawn with the uppercase form, which is
 *     what the block-font look is, not a fallback;
 *   - a character with no glyph is drawn as a filled box, so a missing glyph is obvious rather than
 *     invisible - the one failure mode a silent rasteriser can hide;
 *   - it will never match the browser's font engine, and nothing a user downloads is drawn with it.
 *     The browser draws with the platform's real fonts. This font exists so a test, a contact sheet
 *     or a server-side preview can show what a card *says*.
 */

