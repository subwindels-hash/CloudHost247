/** The box drawn for a character the font does not carry. */
export const MISSING_GLYPH: string[] = ['11111', '10001', '10001', '10001', '10001', '10001', '11111'];

/**
 * The glyph for one character, in the block font's uppercase alphabet.
 *
 * Whitespace has a real (empty) glyph; anything unknown becomes a filled box.
 */
export function glyphFor(character: string): string[] {
  if (character === ' ' || character === '\t') return GLYPHS[' '] ?? [];
  return GLYPHS[character.toUpperCase()] ?? MISSING_GLYPH;
}

/** Whether the font carries a real glyph (as opposed to the missing-glyph box). */
export function hasGlyph(character: string): boolean {
  if (character === ' ' || character === '\t') return true;
  return Boolean(GLYPHS[character.toUpperCase()]);
}
